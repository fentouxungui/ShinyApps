#!/usr/bin/env python3
"""Render catalog/README.md from catalog/catalog.json.

Single source of truth: catalog/catalog.json (itself generated by
.github/workflows/publish-catalog.yml from catalog/apps.yml + each app's
latest GitHub release).

An app entry with no published release (or no matching bundle asset) stays in
the catalog with `"version": ""` and `"artifacts": {}`, and is rendered here as
unavailable instead of being dropped.

Usage
-----
    python3 catalog/render_readme.py              # catalog/catalog.json -> catalog/README.md
    python3 catalog/render_readme.py IN OUT       # explicit input / output paths

The output is deterministic: the only timestamp used is the catalog's own
`updated_at`, so re-running on unchanged data produces byte-identical output
(and therefore no new commit in the publish workflow).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
HOME_REPO = "https://github.com/fentouxungui/ShinyApps"

STATUS_OK = "✅ Available"
STATUS_NO = "⛔ Unavailable"


def human_size(n) -> str:
    try:
        n = float(n)
    except (TypeError, ValueError):
        return "-"
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if n < 1024 or unit == "TB":
            return f"{int(n)} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1024
    return f"{n:.1f} TB"


def esc(s) -> str:
    return str(s or "").replace("|", "\\|").replace("\n", " ").strip()


def link(label: str, url: str) -> str:
    return f"[{label}]({url})" if url else ""


PLATFORM_LABELS = {
    "win-x64": "Windows x64",
    "win-arm64": "Windows arm64",
    "mac-arm64": "macOS arm64",
    "mac-x64": "macOS Intel",
    "linux-x64": "Linux x64",
}


def download_links(art: dict) -> str:
    """Direct artifact links for the platforms this app publishes."""
    art = art or {}
    order = list(PLATFORM_LABELS) + [p for p in art if p not in PLATFORM_LABELS]
    links = []
    for plat in order:
        url = (art.get(plat) or {}).get("url")
        if url:
            links.append(link(PLATFORM_LABELS.get(plat, plat), url))
    return " · ".join(links) or "—"


def is_available(app: dict) -> bool:
    """Available == has at least one published platform bundle."""
    return bool(app.get("artifacts"))


def release_url(app: dict) -> str:
    home = (app.get("homepage") or "").rstrip("/")
    ver = app.get("version")
    if not home or not ver:
        return ""
    return f"{home}/releases/tag/v{ver}"


def render(cat: dict) -> str:
    apps = cat.get("apps", []) or []
    shell = cat.get("shell_min_version", "")
    updated = (cat.get("updated_at") or "").replace("T", " ").replace("Z", " UTC").strip()
    n_unavail = sum(1 for a in apps if not is_available(a))

    out: list[str] = []
    out.append("# ShinyApps Catalog")
    out.append("")
    out.append(
        "A desktop app store for Shiny apps. This page lists every app in the "
        "catalog and is regenerated automatically by the "
        f"[`Publish catalog`]({HOME_REPO}/blob/main/.github/workflows/publish-catalog.yml) workflow."
    )
    out.append("")
    count = f"- **Apps:** {len(apps)}"
    if n_unavail:
        count += f" — {len(apps) - n_unavail} {STATUS_OK} / {n_unavail} {STATUS_NO}"
    out.append(count)
    if shell:
        out.append(f"- **Shell minimum version:** `{shell}`")
    if updated:
        out.append(f"- **Catalog last updated:** {updated}")
    out.append("")
    out.append(
        "> Machine-readable manifest: [`catalog.json`](catalog.json) · "
        "Icons are served from [`icons/`](icons)."
    )
    out.append("")
    out.append("## How to install an app")
    out.append("")
    out.append("1. Download the ZIP for your platform from the table below.")
    out.append("2. Open ShinyApps.")
    out.append("3. Go to **Apps → Install from Bundle…** and select the ZIP "
               "(or drag it onto the launcher).")
    out.append("4. The app appears in the launcher and runs locally — no R "
               "installation and no data upload.")
    out.append("")
    out.append("The ZIP is a ShinyApps app bundle, not a standalone application.")
    out.append("")
    out.append("Windows: Windows 10/11 x64. macOS: Apple Silicon (M1 or newer), "
               "macOS 14+; Intel Macs are not supported.")
    out.append("")
    out.append(f"Don't have ShinyApps yet? Download it from the "
               f"[latest release]({HOME_REPO}/releases/latest).")
    out.append("")

    if not apps:
        out.append("_The catalog is currently empty._")
        out.append("")
        return "\n".join(out)

    out.append("| Icon | App | Status | Version | Download | Links |")
    out.append("|:---:|---|:---:|---:|---|---|")
    for a in apps:
        art = a.get("artifacts", {}) or {}
        status = STATUS_OK if art else STATUS_NO
        ver = esc(a.get("version"))
        ver_cell = f"`{ver}`" if ver else "—"
        downloads = download_links(art)
        links = " · ".join(
            x for x in (
                link("Home", a.get("homepage")),
                link("Docs", a.get("docs")),
                link("Release", release_url(a)),
            ) if x
        ) or "—"
        icon = a.get("icon", "")
        img = f'<img src="{icon}" width="32" alt="{esc(a.get("name"))}">' if icon else ""
        out.append(
            f"| {img} | **{esc(a.get('name'))}**<br>{esc(a.get('description'))} "
            f"| {status} | {ver_cell} | {downloads} | {links} |"
        )
    out.append("")
    out.append("Windows bundles are x64. macOS bundles are arm64 (Apple Silicon, "
               "macOS 14+); Intel Macs are not supported.")
    out.append("")
    out.append("---")
    out.append("")
    out.append("## Apps")
    out.append("")

    for a in apps:
        art = a.get("artifacts", {}) or {}
        ver = esc(a.get("version"))
        out.append(f"### {esc(a.get('name'))}" + (f" `{ver}`" if ver else ""))
        out.append("")
        if not art:
            out.append(f"**Status:** {STATUS_NO} — no published release yet.")
            out.append("")
        if a.get("description"):
            out.append(esc(a["description"]))
            out.append("")
        fields = [
            ("Author", a.get("author")),
            ("License", a.get("license")),
            ("Contact", a.get("email")),
            ("Copyright", a.get("copyright")),
            ("R version", a.get("r_version")),
        ]
        rows = [f"| {k} | {esc(v)} |" for k, v in fields if v]
        if rows:
            out.append("| Field | Value |")
            out.append("|---|---|")
            out.extend(rows)
            out.append("")
        rel = release_url(a)
        if rel:
            out.append(f"Release: {rel}")
            out.append("")
        if art:
            out.append('<details markdown="1"><summary>Downloads &amp; checksums</summary>')
            out.append("")
            out.append("| Platform | File | Size | SHA-256 |")
            out.append("|---|---|---:|---|")
            for plat, info in art.items():
                url = info.get("url", "")
                name = url.rsplit("/", 1)[-1] if url else "-"
                out.append(
                    f"| `{plat}` | [{name}]({url}) | {human_size(info.get('size'))} "
                    f"| `{info.get('sha256') or '-'}` |"
                )
            out.append("")
            out.append("</details>")
            out.append("")

    out.append("---")
    out.append("")
    out.append(
        "_This file is generated. Do not edit it by hand; it will be overwritten "
        "on the next catalog publish._"
    )
    out.append("")
    return "\n".join(out)


def main(argv) -> None:
    src = Path(argv[1]) if len(argv) > 1 else HERE / "catalog.json"
    dst = Path(argv[2]) if len(argv) > 2 else HERE / "README.md"
    cat = json.loads(src.read_text(encoding="utf-8"))
    text = render(cat)
    dst.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {dst} ({len(cat.get('apps', []))} apps)")


if __name__ == "__main__":
    main(sys.argv)
